/*
  Browser-side Logistic Regression inference.
  The model file is generated by ml/train_model.py.
*/

const sigmoid = (z) =>
  1 / (1 + Math.exp(-Math.max(-35, Math.min(35, z))));

export function predictMessage(message, model) {
  if (
    !model ||
    !model.trained ||
    !model.vocabulary ||
    !model.idf ||
    !model.coefficients
  ) {
    throw new Error(
      "The trained model is not loaded. Train the model first."
    );
  }

  // Tokenization
  const tokens =
    message.toLowerCase().match(/[a-z0-9_]{2,}/g) || [];

  // Generate unigrams and adjacent bigrams
  const terms = [...tokens];

  for (let i = 0; i < tokens.length - 1; i++) {
    terms.push(`${tokens[i]} ${tokens[i + 1]}`);
  }

  // Count terms present in the trained vocabulary
  const counts = {};

  terms.forEach((term) => {
    if (model.vocabulary[term] !== undefined) {
      counts[term] = (counts[term] || 0) + 1;
    }
  });

  // TF-IDF calculation
  const weighted = [];
  let normSquared = 0;

  Object.entries(counts).forEach(([token, count]) => {
    const index = model.vocabulary[token];

    const tf = 1 + Math.log(count);
    const value = tf * Number(model.idf[index] || 0);

    weighted.push({ token, index, value });
    normSquared += value * value;
  });

  const norm = Math.sqrt(normSquared) || 1;

  // Logistic Regression score
  let score = Number(model.intercept || 0);

  const contributions = [];

  weighted.forEach(({ token, index, value }) => {
    const tfidf = value / norm;

    const contribution =
      tfidf * Number(model.coefficients[index] || 0);

    score += contribution;

    if (Math.abs(contribution) > 0.005) {
      contributions.push({
        token,
        contribution
      });
    }
  });

  contributions.sort(
    (a, b) =>
      Math.abs(b.contribution) - Math.abs(a.contribution)
  );

  // Convert score into probability
  const scamProbability = sigmoid(score);
  const genuineProbability = 1 - scamProbability;

  const medium = Number(model.thresholds?.medium ?? 0.40);
  const high = Number(model.thresholds?.high ?? 0.75);

  const risk =
    scamProbability >= high
      ? "High"
      : scamProbability >= medium
      ? "Medium"
      : "Low";

  return {
    scamProbability,
    genuineProbability,
    risk,
    indicators: contributions.slice(0, 6),
    score
  };
}